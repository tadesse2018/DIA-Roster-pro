export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Language>(() => {
    return (localStorage.getItem('school_lang') as Language) || 'am';
  });

  const setLang = (newLang: Language) => {
    setLangState(newLang);
    localStorage.setItem('school_lang', newLang);
  };

  // Explicit inline translate helper
  const t = (amText: string, enText: string) => {
    return lang === 'am' ? amText : enText;
  };

  // Smart dynamic translate helper
  const tx = (rawText: string): string => {
    if (!rawText) return rawText;
    
    const text = rawText.trim();
    
    // Check for emojis/icons at the start
    const prefixRegex = /^([\u2300-\u23FF\u2B00-\u2BFF\u2100-\u219F\u2600-\u26FF\uD83C-\uDBFF\uDC00-\uDFFF]+)(.*)$/;
    let icon = "";
    let rest = text;
    
    const prefixMatch = text.match(prefixRegex);
    if (prefixMatch) {
      icon = prefixMatch[1] + " ";
      rest = prefixMatch[2].trim();
    }

    // Format check: "Amharic (English)" optionally followed by punctuation like ":" or "፡"
    const parenRegex = /^([^(]+)\(([^)]+)\)([\s\S]*)$/;
    const match = rest.match(parenRegex);
    
    if (match) {
      const amPart = match[1].trim();
      const enPart = match[2].trim();
      const trail = match[3]; // Any trailing punctuation
      
      return lang === 'am' ? `${icon}${amPart}${trail}` : `${icon}${enPart}${trail}`;
    }

    // Dictionary fallback
    const dict = TRANSLATION_DICTIONARY[rest];
    if (dict) {
      return lang === 'am' ? `${icon}${dict.am}` : `${icon}${dict.en}`;
    }

    return text;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, tx }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
